/// Bit-exact PRNG matching FFmpeg's `av_lfg` with seed = 0.
#[derive(Clone, Debug)]
pub struct AvLfg {
    state: [u32; 64],
    index: usize,
}

impl AvLfg {
    pub fn new() -> Self {
        Self {
            state: LFG_INIT_STATE_0,
            index: 0,
        }
    }

    #[inline]
    pub fn get(&mut self) -> u32 {
        let a = self.state[(self.index.wrapping_sub(24)) & 63]
            .wrapping_add(self.state[(self.index.wrapping_sub(55)) & 63]);
        self.state[self.index & 63] = a;
        self.index = (self.index + 1) & 63;
        a
    }
}

