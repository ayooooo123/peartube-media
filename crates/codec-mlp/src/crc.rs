#[inline]
pub fn av_crc(table: &[u32; 256], mut crc: u32, buf: &[u8]) -> u32 {
    for &b in buf {
        crc = table[((crc as u8) ^ b) as usize] ^ (crc >> 8);
    }
    crc
}

#[inline]
pub fn checksum8(buf: &[u8]) -> u8 {
    if buf.is_empty() {
        return 0;
    }
    let crc = av_crc(&CRC_63, 0x3c, &buf[..buf.len() - 1]);
    (crc as u8) ^ buf[buf.len() - 1]
}

#[inline]
pub fn checksum16(buf: &[u8]) -> u16 {
    if buf.len() < 2 {
        return 0;
    }
    let crc = av_crc(&CRC_2D, 0, &buf[..buf.len() - 2]);
    let end = u16::from_le_bytes([buf[buf.len() - 2], buf[buf.len() - 1]]);
    (crc as u16) ^ end
}

#[inline]
pub fn restart_checksum(buf: &[u8], bit_size: usize) -> u8 {
    let num_bytes = (bit_size + 2) / 8;
    if buf.is_empty() || num_bytes == 0 || num_bytes > buf.len() {
        return 0;
    }
    let mut crc = av_crc(&CRC_1D, (buf[0] & 0xC0) as u32, &buf[..num_bytes - 1]);
    crc ^= buf[num_bytes - 1] as u32;

    for i in 0..((bit_size + 2) & 7) {
        crc <<= 1;
        if (crc & 0x100) != 0 {
            crc ^= 0x11D;
        }
        if num_bytes < buf.len() {
            crc ^= ((buf[num_bytes] >> (7 - i)) & 1) as u32;
        }
    }
    crc as u8
}

#[inline]
pub fn calculate_parity(buf: &[u8]) -> u8 {
    buf.iter().fold(0u8, |acc, &b| acc ^ b)
}

#[inline]
pub fn xor_32_to_8(val: u32) -> u8 {
    let b = val.to_ne_bytes();
    b[0] ^ b[1] ^ b[2] ^ b[3]
}
