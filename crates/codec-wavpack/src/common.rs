#[inline]
pub fn wp_exp2(val: i16) -> i32 {
    let (uval, neg) = if val < 0 {
        (val.wrapping_neg() as u16, true)
    } else {
        (val as u16, false)
    };
    let mut res = (EXP2_TABLE[(uval & 0xFF) as usize] as i32) | 0x100;
    let shift = uval >> 8;
    if shift > 31 {
        return i32::MIN;
    }
    res = if shift > 9 {
        res.wrapping_shl((shift - 9) as u32)
    } else {
        res >> (9 - shift)
    };
    if neg {
        res.wrapping_neg()
    } else {
        res
    }
}

#[inline]
pub fn wp_log2(mut val: u32) -> i32 {
    if val == 0 {
        return 0;
    }
    if val == 1 {
        return 256;
    }
    val = val.wrapping_add(val >> 9);
    let bits = (32 - val.leading_zeros()) as i32;
    let table_val = if bits < 9 {
        LOG2_TABLE[((val << (9 - bits)) & 0xFF) as usize] as i32
    } else {
        LOG2_TABLE[((val >> (bits - 9)) & 0xFF) as usize] as i32
    };
    (bits << 8) + table_val
}
